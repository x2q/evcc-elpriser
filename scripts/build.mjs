#!/usr/bin/env node
// Generates every YAML file of this repository from src/elpriser.jq, so the jq
// program exists exactly once.
//
//   node scripts/build.mjs          write the files
//   node scripts/build.mjs --check  fail if a file on disk differs (used by the tests)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jqSource = readFileSync(join(root, 'src/elpriser.jq'), 'utf8').trimEnd();
export const zones = JSON.parse(readFileSync(join(root, 'src/zones.json'), 'utf8'));

export const DK_MODES = [
  'inkl_alt',
  'spot_inkl',
  'spot_ex',
  'inkl_alt_minus',
  'inkl_alt_elvarme',
  'net_inkl_alt',
  'net_inkl_alt_elvarme',
  'net_inkl_tarif',
];

const indent = (text, n) =>
  text
    .split('\n')
    .map((l) => (l === '' ? l : ' '.repeat(n) + l))
    .join('\n');

/** The jq program with the two settings filled in (literals or template expressions). */
export function jqProgram({ local, actualOnly }) {
  return jqSource.replace('__LOCAL_CURRENCY__', local).replace('__ACTUAL_ONLY__', actualOnly);
}

/** A complete evcc.yaml `tariffs:` block. */
function example({ title, lines, zone, uri, currency, local, actualOnly = false, grid = 'grid', extra = [] }) {
  const header = [
    `# ${title}`,
    ...lines.map((l) => `# ${l}`),
    '#',
    '# Merge the block into your evcc.yaml. Needs evcc with the "custom" tariff, a',
    '# network connection to elpriser.org and nothing else: no account, no API key.',
    '# Generated by scripts/build.mjs from src/elpriser.jq - do not edit by hand.',
  ];
  return (
    header.join('\n') +
    '\n' +
    [
      'tariffs:',
      `  currency: ${currency}`,
      `  ${grid}:`,
      '    type: custom',
      ...extra.map((l) => '    ' + l),
      '    forecast:',
      '      source: http',
      `      uri: ${uri}`,
      '      cache: 1h',
      '      jq: |',
      indent(jqProgram({ local, actualOnly }), 8),
      '    interval: 1h',
    ].join('\n') +
    '\n'
  );
}

